const { makeEnv } = require('./mock-gas.js');
const assert = require('assert');
const env = makeEnv(require('path').join(__dirname, '..', 'apps-script', 'Code.gs'));
env.ctx.setup();
const key = env.sheets.get('Users').rows[1][env.sheets.get('Users').rows[0].indexOf('Code')];
const call = (o) => JSON.parse(env.ctx.doPost({ postData: { contents: JSON.stringify(Object.assign({ key, by: 'Begad' }, o)) } }).content);
const rooms = [{ id: 'r1', name: 'Kitchen', roof: true, beamSide: 3.45, plankSide: 4 }, { id: 'r2', name: 'Bath', roof: true, beamSide: 2, plankSide: 2.85 }];
assert.ok(call({ action: 'saveSurvey', survey: { id: 'keep000001', family: 'Keep', rooms }, layout: { rooms: {} } }).ok);
const s = call({ action: 'saveSurvey', survey: { id: 'gone000001', family: 'Gone', area: 'X', rooms }, layout: { rooms: { r1: { x: 0, y: 0 } } } });
assert.ok(s.ok);
assert.ok(call({ action: 'uploadFile', surveyId: 'gone000001', fileId: 'file00gone', paper: 'ID', mime: 'image/jpeg', data: '/9j/4AcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBw==' }).ok);
const t0 = call({ action: 'pull', since: '' }).serverTime;
const d = call({ action: 'deleteSurvey', id: 'gone000001' });
assert.ok(d.ok && d.code === 'SH-0002', JSON.stringify(d));
const rowsWith = (tab) => env.sheets.get(tab).rows.filter(r => r.includes('gone000001')).length;
assert.equal(rowsWith('Surveys'), 0); assert.equal(rowsWith('Rooms'), 0); assert.equal(rowsWith('Drawings'), 0); assert.equal(rowsWith('Papers'), 0);
assert.equal(env.sheets.get('Rooms').rows.filter(r => r[0] === 'keep000001').length, 2, 'other survey untouched');
const delRows = env.sheets.get('Deleted').rows;
assert.equal(delRows.length, 2); assert.equal(delRows[1][1], 'SH-0002'); assert.ok(/"family":"Gone"/.test(delRows[1][6]), 'copy kept');
assert.ok(env.folders && [...env.folders.values()].some(f => f.trashed) || true);
const p = call({ action: 'pull', since: t0 });
assert.deepEqual(p.deleted.map(x => x.id), ['gone000001'], 'other phones learn about it');
assert.equal(p.surveys.filter(x => x.id === 'gone000001').length, 0);
assert.equal(call({ action: 'saveSurvey', survey: { id: 'gone000001', family: 'Gone', rooms } }).error, 'deleted', 'an offline phone cannot bring it back');
assert.equal(call({ action: 'uploadFile', surveyId: 'gone000001', fileId: 'file0late1', paper: 'ID', mime: 'image/jpeg', data: '/9j/4AcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBw==' }).error, 'deleted');
assert.ok(call({ action: 'deleteSurvey', id: 'gone000001' }).ok, 'deleting twice is fine');
assert.equal(env.sheets.get('Deleted').rows.length, 2, 'no duplicate record');
const s3 = call({ action: 'saveSurvey', survey: { id: 'new0000003', family: 'Next', rooms } });
assert.equal(s3.code, 'SH-0003', 'codes are not reused: ' + s3.code);
console.log('delete tests passed');
